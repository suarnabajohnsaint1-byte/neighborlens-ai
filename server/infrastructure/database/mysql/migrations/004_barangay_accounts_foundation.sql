ALTER TABLE users
  ADD COLUMN barangay_id INT UNSIGNED NULL AFTER barangay,
  ADD COLUMN status ENUM('active', 'suspended') NOT NULL DEFAULT 'active' AFTER full_name,
  ADD COLUMN token_version INT UNSIGNED NOT NULL DEFAULT 0 AFTER status,
  ADD CONSTRAINT fk_users_barangay FOREIGN KEY (barangay_id) REFERENCES barangays(id) ON DELETE RESTRICT;

UPDATE users u
  JOIN barangays b ON b.name = TRIM(u.barangay)
  SET u.barangay_id = b.id, u.barangay = b.name, u.updated_at = u.updated_at
  WHERE u.barangay_id IS NULL;

ALTER TABLE users
  ADD CONSTRAINT chk_users_official_barangay CHECK (role <> 'barangay' OR barangay_id IS NOT NULL);

CREATE INDEX idx_users_role_status ON users(role, status);

UPDATE reports r
  JOIN barangays b ON b.name = TRIM(r.barangay)
  SET r.barangay_id = b.id, r.barangay = b.name, r.updated_at = r.updated_at
  WHERE r.barangay_id IS NULL;

